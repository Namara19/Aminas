/* Aminas service worker: precaches the whole game so it launches and plays offline.
   The VERSION and PRECACHE list are generated by `node tools/stamp.js` (run it after any file change). */
const VERSION = '1660cc93b0';
const PRECACHE = [
  "./",
  "./apple-touch-icon.png",
  "./art.js",
  "./audio.js",
  "./data.js",
  "./favicon-32.png",
  "./icon-192.png",
  "./icon-512.png",
  "./icon-maskable-512.png",
  "./index.html",
  "./main.js",
  "./manifest.webmanifest",
  "./rules.js",
  "./state.js",
  "./story.js",
  "./style.css",
  "./ui.js",
  "./ui2.js"
];
const CACHE = 'aminas-' + VERSION;

self.addEventListener('install', (e) => {
  e.waitUntil(caches.open(CACHE).then((c) => c.addAll(PRECACHE)).then(() => self.skipWaiting()));
});
self.addEventListener('activate', (e) => {
  e.waitUntil(caches.keys().then((keys) => Promise.all(keys.filter((k) => k.startsWith('aminas-') && k !== CACHE).map((k) => caches.delete(k)))).then(() => self.clients.claim()));
});
self.addEventListener('fetch', (e) => {
  const req = e.request;
  if (req.method !== 'GET' || new URL(req.url).origin !== self.location.origin) return;
  // Pages: network-first (so updates arrive), falling back to the cached shell when offline.
  if (req.mode === 'navigate') {
    e.respondWith(fetch(req).then((r) => { const copy = r.clone(); caches.open(CACHE).then((c) => c.put('./index.html', copy)); return r; }).catch(() => caches.match('./index.html').then((r) => r || caches.match('./'))));
    return;
  }
  // Assets: cache-first.
  e.respondWith(caches.match(req, { ignoreSearch: true }).then((hit) => hit || fetch(req).then((r) => { if (r.ok) { const copy = r.clone(); caches.open(CACHE).then((c) => c.put(req, copy)); } return r; })));
});
